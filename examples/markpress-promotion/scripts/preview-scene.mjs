import fs from 'node:fs';
import path from 'node:path';
import {stop} from 'esbuild';
import {bundle} from '@remotion/bundler';
import {selectComposition,renderMedia} from '@remotion/renderer';
import {validateConfig,motionEvents} from './config.mjs';
import {buildAudio} from './audio.mjs';
import {run} from './lib.mjs';
const root=process.cwd(),c=validateConfig(JSON.parse(fs.readFileSync('config.json')),root);
const first=Number(process.argv[2]),last=Number(process.argv[3]);
if(!Number.isInteger(first)||!Number.isInteger(last)||first<0||last<first||last>=c.duration*c.fps)throw new Error('Usage: node scripts/preview-scene.mjs FIRST_FRAME LAST_FRAME (inclusive)');
const out=path.join(root,'out');fs.mkdirSync(path.join(out,'qa'),{recursive:true});c.motionEvents=motionEvents(c);
const serveUrl=await bundle({entryPoint:path.join(root,'src/index.ts'),publicDir:path.join(root,'public')});stop();
const common={serveUrl,inputProps:{config:c},browserExecutable:process.env.PROMOTION_BROWSER||process.env.VIDEO_CREATE_BROWSER||undefined},composition=await selectComposition({...common,id:'ProductFilm'});
const silent=path.join(out,'qa','preview-silent.mp4'),output=path.join(out,'qa','handoff.mp4');
await renderMedia({...common,composition,frameRange:[first,last],codec:'h264',colorSpace:'bt709',pixelFormat:'yuv420p',crf:18,concurrency:2,outputLocation:silent});
const audio=await buildAudio(root,c,out);
if(audio)await run('ffmpeg',['-y','-v','error','-i',silent,'-ss',String(first/c.fps),'-i',audio,'-map','0:v','-map','1:a','-c:v','copy','-c:a','aac','-t',String((last-first+1)/c.fps),output]);else fs.copyFileSync(silent,output);
fs.rmSync(silent);stop();console.log('Encoded handoff preview ready');process.exit(0);
